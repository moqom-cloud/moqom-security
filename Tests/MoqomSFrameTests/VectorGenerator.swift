// Generates the MoQ vectors in vectors/sframe from this implementation.
//
//     MOQOM_WRITE_VECTORS=1 swift test --filter SFrameVectorGeneration
//
// Without the variable it regenerates in memory and requires the result to
// equal what is checked in, so regenerating is a no-op unless the format
// changes.

import Foundation
import Testing

@testable import MoqomSFrame

private let source = "Generated by the Swift MoqomSFrame implementation: Tests/MoqomSFrameTests/VectorGenerator.swift"

private func baseKey(_ suite: SFrameCipherSuite) -> Data {
    Data((0 ..< suite.keyLength).map { UInt8($0) })
}

private func payload(_ count: Int, seed: UInt8 = 0) -> Data {
    Data((0 ..< count).map { UInt8(truncatingIfNeeded: $0 &* 7 &+ Int(seed)) })
}

/// The shape MOQOM's video objects have: capture time and temporal layer.
private let video = SFrameMetadata(
    group: 5,
    object: 2,
    priority: 64,
    properties: [.integer(0x78, 1_000_000), .integer(0x7A, 1)]
)

/// A keyframe carrying its decoder configuration and a catalog disclosure.
private let keyframe = SFrameMetadata(
    group: 300,
    object: 0,
    priority: 0,
    properties: [.bytes(0x79, payload(40, seed: 9)), .integer(0x78, 33_366), .bytes(0x7D, Data("video/720p".utf8))]
)

private let bare = SFrameMetadata(group: 0, object: 0, priority: 128)

private func sealed(_ key: SFrameKey, counter: UInt64, _ plaintext: Data, _ metadata: SFrameMetadata) throws -> Data {
    let header = SFrameHeader(keyID: key.keyID, counter: counter).encoded
    return try header + key.seal(plaintext, counter: counter, aad: header + metadata.encoded())
}

enum SFrameVectorGenerator {
    static func files() throws -> [(String, Data)] {
        try [
            ("metadata.json", encodeVectors(metadata())),
            ("kid.json", encodeVectors(keyIDs())),
            ("nonce.json", encodeVectors(nonces())),
            ("seal-open.json", encodeVectors(seals())),
            ("open.json", encodeVectors(opens())),
            ("replay.json", encodeVectors(replays())),
        ]
    }

    static func metadata() throws -> VectorFile<MetadataCase> {
        let limit = SFrameMetadata.varIntMaximum
        let valid: [(String, SFrameMetadata)] = [
            ("bare", SFrameMetadata(group: 0, object: 0, priority: 0)),
            ("video", video),
            ("keyframe", keyframe),
            ("varint-1-byte-max", SFrameMetadata(group: 63, object: 63, priority: 255)),
            ("varint-2-byte", SFrameMetadata(group: 64, object: 16383, priority: 1)),
            ("varint-4-byte", SFrameMetadata(group: 16384, object: 1_073_741_823, priority: 2)),
            ("varint-8-byte", SFrameMetadata(group: 1_073_741_824, object: limit, priority: 3)),
            (
                "properties-sorted-by-type",
                SFrameMetadata(group: 1, object: 1, priority: 1, properties: [.integer(0x7A, 2), .integer(0x78, 9), .integer(0x7C, 1)])
            ),
            (
                "repeated-type-keeps-order",
                SFrameMetadata(group: 1, object: 2, priority: 3, properties: [.bytes(0x7F, Data([0xBB])), .integer(0x78, 4), .bytes(0x7F, Data([0xAA]))])
            ),
            ("empty-bytes-property", SFrameMetadata(group: 1, object: 0, priority: 0, properties: [.bytes(0x79, Data())])),
            ("bytes-property-2-byte-length", SFrameMetadata(group: 2, object: 0, priority: 0, properties: [.bytes(0x7D, payload(300))])),
            ("large-type-delta", SFrameMetadata(group: 0, object: 0, priority: 0, properties: [.integer(0x10, 1), .integer(limit - 1, limit)])),
        ]
        let invalid: [(String, SFrameMetadata)] = [
            ("even-type-with-bytes", SFrameMetadata(group: 0, object: 0, priority: 0, properties: [.bytes(0x78, Data([1]))])),
            ("odd-type-with-integer", SFrameMetadata(group: 0, object: 0, priority: 0, properties: [.integer(0x79, 1)])),
            ("group-beyond-varint", SFrameMetadata(group: limit + 1, object: 0, priority: 0)),
            ("object-beyond-varint", SFrameMetadata(group: 0, object: UInt64.max, priority: 0)),
            ("integer-beyond-varint", SFrameMetadata(group: 0, object: 0, priority: 0, properties: [.integer(0x78, limit + 1)])),
            ("type-beyond-varint", SFrameMetadata(group: 0, object: 0, priority: 0, properties: [.integer(limit + 1, 0)])),
        ]
        var cases = try valid.map {
            MetadataCase(name: $0.0, metadata: MetadataVector($0.1), encoded_hex: try $0.1.encoded().hexString)
        }
        for (name, metadata) in invalid {
            #expect(throws: SFrameError.invalidMetadata) { _ = try metadata.encoded() }
            cases.append(MetadataCase(name: name, metadata: MetadataVector(metadata), error: "invalid_metadata"))
        }
        return VectorFile(
            description: "The canonical encoding of MoQ object metadata bound into the AEAD tag, and metadata that has none.",
            source: source,
            cases: cases
        )
    }

    static func keyIDs() -> VectorFile<KeyIDCase> {
        let pairs: [(UInt32, UInt64)] = [
            (0, 0), (0, 7), (0, 15), (0, 16), (1, 0), (3, 14), (7, 14), (20, 14), (3, 15),
            (5, 15), (33, 17), (51, 17), (4095, 1_000_003), (UInt32.max, UInt64.max),
        ]
        return VectorFile(
            description: "RFC 9605 §5.2 KIDs for MLS members: leaf index above a four-bit epoch tag, and the header each makes at counter 0.",
            source: source,
            cases: pairs.map { leaf, epoch in
                let kid = SFrameKeyID.mls(leaf: leaf, epoch: epoch)
                return KeyIDCase(
                    name: "leaf-\(leaf)-epoch-\(epoch)",
                    leaf: leaf,
                    epoch: epoch,
                    kid: kid,
                    epoch_tag: SFrameKeyID.epochTag(of: kid),
                    header_hex: SFrameHeader(keyID: kid, counter: 0).encoded.hexString
                )
            }
        )
    }

    static func nonces() -> VectorFile<NonceCase> {
        let counters: [UInt64] = [0, 1, 7, 8, 0xFF, 0x100, 0xFFFF_FFFF, 0x1_0000_0000, UInt64.max - 1, UInt64.max]
        var cases: [NonceCase] = []
        for suite in SFrameCipherSuite.allCases {
            for kid: UInt64 in [0x3E, 0xFFFF_FFFF_FFFF_FFFF] {
                let key = SFrameKey(keyID: kid, baseKey: baseKey(suite), suite: suite)
                for ctr in counters {
                    cases.append(NonceCase(
                        name: String(format: "%04x-kid-%llx-ctr-%llx", suite.rawValue, kid, ctr),
                        cipher_suite: suite.rawValue,
                        kid: kid,
                        ctr: ctr,
                        base_key_hex: baseKey(suite).hexString,
                        sframe_key_hex: key.key.withUnsafeBytes { Data($0) }.hexString,
                        sframe_salt_hex: key.salt.hexString,
                        nonce_hex: key.nonce(counter: ctr).hexString,
                        header_hex: SFrameHeader(keyID: kid, counter: ctr).encoded.hexString
                    ))
                }
            }
        }
        return VectorFile(
            description: "Key and salt derivation per KID and suite, and the nonce (salt XOR counter) and header at counters across the 64-bit range.",
            source: source,
            cases: cases
        )
    }

    static func seals() throws -> VectorFile<SealCase> {
        var cases: [SealCase] = []
        for suite in SFrameCipherSuite.allCases {
            let shapes: [(String, UInt64, SFrameMetadata, [Data])] = [
                ("video", 1, video, [payload(1), payload(60, seed: 1), payload(1200, seed: 2)]),
                ("keyframe-extended-kid", SFrameKeyID.mls(leaf: 3, epoch: 14), keyframe, [payload(4096, seed: 3)]),
                ("bare-empty-payload", 0, bare, [Data()]),
                ("max-kid", UInt64.max, video, [payload(16, seed: 4)]),
                ("counter-crosses-into-extended", 2, video, (0 ..< 10).map { payload(8, seed: UInt8($0)) }),
            ]
            for (name, kid, metadata, plaintexts) in shapes {
                let context = SFrameContext(suite: suite, keyID: kid, baseKey: baseKey(suite))
                let seals = try plaintexts.map {
                    SealCase.Seal(pt_hex: $0.hexString, object_hex: try context.seal($0, metadata: metadata).hexString)
                }
                cases.append(SealCase(
                    name: String(format: "%04x-", suite.rawValue) + name,
                    cipher_suite: suite.rawValue,
                    kid: kid,
                    base_key_hex: baseKey(suite).hexString,
                    metadata: MetadataVector(metadata),
                    seals: seals
                ))
            }
        }
        return VectorFile(
            description: "Context seal and open per suite: a fresh context sealing each plaintext in order (counters from 0) must produce each object, and a fresh context must open each back.",
            source: source,
            cases: cases
        )
    }

    static func opens() throws -> VectorFile<OpenCase> {
        var cases: [OpenCase] = []
        for suite in SFrameCipherSuite.allCases {
            let kid: UInt64 = 0x3E
            let key = SFrameKey(keyID: kid, baseKey: baseKey(suite), suite: suite)
            let plaintext = payload(32, seed: 5)
            let object = try sealed(key, counter: 0x4567, plaintext, keyframe)
            let headerLength = try SFrameHeader.read(from: object).1

            func add(_ name: String, _ object: Data, _ metadata: SFrameMetadata = keyframe, error: String? = nil) {
                cases.append(OpenCase(
                    name: String(format: "%04x-", suite.rawValue) + name,
                    cipher_suite: suite.rawValue,
                    kid: kid,
                    base_key_hex: baseKey(suite).hexString,
                    metadata: MetadataVector(metadata),
                    object_hex: object.hexString,
                    pt_hex: error == nil ? plaintext.hexString : nil,
                    error: error
                ))
            }

            add("honest", object)

            var changed = keyframe
            changed.group += 1
            add("group-changed", object, changed, error: "authentication_failure")
            changed = keyframe
            changed.object += 1
            add("object-changed", object, changed, error: "authentication_failure")
            changed = keyframe
            changed.priority = 1
            add("priority-changed", object, changed, error: "authentication_failure")
            changed = keyframe
            changed.properties[1] = .integer(0x78, 33_367)
            add("capture-time-changed", object, changed, error: "authentication_failure")
            changed = keyframe
            changed.properties[0] = .bytes(0x79, payload(40, seed: 10))
            add("configuration-changed", object, changed, error: "authentication_failure")
            changed = keyframe
            changed.properties[2] = .bytes(0x7D, Data("video/360p".utf8))
            add("disclosure-changed", object, changed, error: "authentication_failure")
            changed = keyframe
            changed.properties.append(.integer(0x7A, 0))
            add("property-added", object, changed, error: "authentication_failure")
            changed = keyframe
            changed.properties.removeLast()
            add("property-removed", object, changed, error: "authentication_failure")
            changed = keyframe
            changed.properties[1] = .integer(0x7A, 33_366)
            add("property-type-changed", object, changed, error: "authentication_failure")
            changed = keyframe
            changed.properties.reverse()
            add("property-order-is-canonical", object, changed)

            var damaged = object
            damaged[headerLength] ^= 0x01
            add("ciphertext-bit-flipped", damaged, error: "authentication_failure")
            damaged = object
            damaged[damaged.endIndex - 1] ^= 0x80
            add("tag-bit-flipped", damaged, error: "authentication_failure")
            add(
                "counter-changed",
                SFrameHeader(keyID: kid, counter: 0x4568).encoded + object.dropFirst(headerLength),
                error: "authentication_failure"
            )
            add(
                "kid-changed",
                SFrameHeader(keyID: kid + 1, counter: 0x4567).encoded + object.dropFirst(headerLength),
                error: "unknown_key"
            )
            add("tag-truncated", object.dropLast(1), error: "authentication_failure")
            add("header-only", object.prefix(headerLength), error: "authentication_failure")
            add("shorter-than-tag", object.prefix(headerLength + suite.tagLength - 1), error: "authentication_failure")
            add("empty", Data(), error: "malformed_header")
            add("kid-truncated", Data([0xB8, 0x3E]), error: "malformed_header")
            add("counter-truncated", Data([0x0B, 0x00, 0x01]), error: "malformed_header")
            add(
                "invalid-metadata",
                object,
                SFrameMetadata(group: 0, object: 0, priority: 0, properties: [.integer(0x79, 1)]),
                error: "invalid_metadata"
            )

            let other: SFrameCipherSuite = suite == .aes256GcmSha512 ? .aes128GcmSha256 : .aes256GcmSha512
            let otherKey = SFrameKey(keyID: kid, baseKey: baseKey(suite), suite: other)
            add("sealed-under-other-suite", try sealed(otherKey, counter: 0x4567, plaintext, keyframe), error: "authentication_failure")
            let strangerKey = SFrameKey(keyID: kid, baseKey: Data(repeating: 0xEE, count: suite.keyLength), suite: suite)
            add("sealed-under-other-base-key", try sealed(strangerKey, counter: 0x4567, plaintext, keyframe), error: "authentication_failure")

            // KID 0x3E and CTR 3 in more bytes than they need. The tag covers the
            // header as sent, so this opens.
            let nonMinimal = Data([0x99, 0x00, 0x3E, 0x00, 0x03])
            let nonMinimalObject = try nonMinimal + key.seal(plaintext, counter: 3, aad: nonMinimal + keyframe.encoded())
            add("non-minimal-header", nonMinimalObject)
        }
        return VectorFile(
            description: "Opening one object with a fresh context: every metadata field change, every header or ciphertext change, and truncated or malformed input.",
            source: source,
            cases: cases
        )
    }

    static func replays() throws -> VectorFile<ReplayCase> {
        enum Step { case open(UInt64), forged(UInt64) }
        typealias Expect = String?
        let sequences: [(String, UInt64, [(Step, Expect)])] = [
            ("duplicate", 1024, [(.open(0), nil), (.open(0), "replay")]),
            (
                "reordering-within-window",
                1024,
                [3, 1, 0, 7, 2, 6, 4, 5].map { (.open($0), nil) } + [(.open(5), "replay")]
            ),
            ("window-64-edge", 64, [(.open(100), nil), (.open(37), nil), (.open(36), "replay"), (.open(37), "replay")]),
            ("window-8-edge", 8, [(.open(100), nil), (.open(93), nil), (.open(92), "replay")]),
            ("window-1024-edge", 1024, [(.open(2000), nil), (.open(977), nil), (.open(976), "replay"), (.open(977), "replay")]),
            (
                "window-1024-duplicates",
                1024,
                [(.open(2000), nil), (.open(1500), nil), (.open(1063), nil), (.open(1500), "replay"),
                 (.open(1063), "replay"), (.open(2000), "replay"), (.open(1064), nil)]
            ),
            (
                "window-1024-far-ahead",
                1024,
                [(.open(10), nil), (.open(1_000_000), nil), (.open(999_000), nil), (.open(5_000_000_000), nil),
                 (.open(4_999_998_977), nil), (.open(4_999_998_976), "replay"), (.open(1_000_000), "replay")]
            ),
            ("window-capped-at-65536", 1_000_000, [(.open(200_000), nil), (.open(134_465), nil), (.open(134_464), "replay")]),
            (
                "jump-forward-clears-history",
                1024,
                [(.open(1), nil), (.open(500), nil), (.open(499), nil), (.open(500), "replay"), (.open(1), "replay")]
            ),
            (
                "forgery-does-not-consume-counter",
                1024,
                [(.forged(5), "authentication_failure"), (.open(5), nil), (.open(5), "replay")]
            ),
            ("top-of-counter-space", 1024, [(.open(UInt64.max - 1), nil), (.open(UInt64.max), nil), (.open(UInt64.max), "replay")]),
        ]

        var cases: [ReplayCase] = []
        for suite in SFrameCipherSuite.allCases {
            let kid: UInt64 = 9
            let key = SFrameKey(keyID: kid, baseKey: baseKey(suite), suite: suite)
            for (name, window, script) in sequences {
                let steps = try script.map { step, expect in
                    switch step {
                    case let .open(counter):
                        let plaintext = payload(12, seed: UInt8(truncatingIfNeeded: counter))
                        return ReplayCase.Step(
                            object_hex: try sealed(key, counter: counter, plaintext, video).hexString,
                            pt_hex: expect == nil ? plaintext.hexString : nil,
                            error: expect
                        )
                    case let .forged(counter):
                        var object = try sealed(key, counter: counter, payload(12), video)
                        object[object.endIndex - 1] ^= 0x01
                        return ReplayCase.Step(object_hex: object.hexString, error: expect)
                    }
                }
                cases.append(ReplayCase(
                    name: String(format: "%04x-", suite.rawValue) + name,
                    cipher_suite: suite.rawValue,
                    kid: kid,
                    base_key_hex: baseKey(suite).hexString,
                    replay_window: window,
                    metadata: MetadataVector(video),
                    steps: steps
                ))
            }
        }
        return VectorFile(
            description: "Replay window: one context with the given window opens each object in order, and each either opens or fails as stated.",
            source: source,
            cases: cases
        )
    }
}

@Suite("SFrame vector generation")
struct SFrameVectorGeneration {
    @Test("regenerating the MoQ vectors changes nothing")
    func regenerate() throws {
        let write = ProcessInfo.processInfo.environment["MOQOM_WRITE_VECTORS"] == "1"
        for (name, data) in try SFrameVectorGenerator.files() {
            let url = vectorDirectory.appending(path: name)
            if write {
                try data.write(to: url)
            } else {
                #expect(try Data(contentsOf: url) == data, "\(name) is stale; regenerate it")
            }
        }
    }
}
