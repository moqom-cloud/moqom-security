//! Writes vectors/mls/mls-crypto-rust.json: this crate's ML-KEM-768 and
//! X-Wing HPKE and ML-DSA-65 output, for Swift and Go to open and verify. Run with
//! `MOQOM_MLS_GENERATE=1 cargo test -p moqom-mls --test generate`. AWS-LC
//! takes no caller randomness, so regenerating changes the ciphertexts and
//! signatures; the file is a recorded transcript.

use moqom_mls::CipherSuite;
use serde_json::{Value, json};

fn hex(data: &[u8]) -> String {
    data.iter().map(|b| format!("{b:02x}")).collect()
}

fn fixed(name: &str, n: usize) -> Vec<u8> {
    let mut out = Vec::new();
    let mut block = 0u8;
    while out.len() < n {
        let input = [format!("moqom-mls {name}").as_bytes(), &[block]].concat();
        out.extend_from_slice(
            aws_lc_rs::digest::digest(&aws_lc_rs::digest::SHA512, &input).as_ref(),
        );
        block += 1;
    }
    out.truncate(n);
    out
}

fn with(base: &Value, fields: Value) -> Value {
    let mut out = base.clone();
    out.as_object_mut()
        .unwrap()
        .extend(fields.as_object().unwrap().clone());
    out
}

#[test]
fn generate_vectors() {
    if std::env::var("MOQOM_MLS_GENERATE").as_deref() != Ok("1") {
        return;
    }
    let suite = CipherSuite::MLDSA;
    let seed = fixed("rust signature seed", 32);
    let content = fixed("rust content", 64);
    let signature = suite
        .sign_with_label(&seed, "GroupInfoTBS", &content)
        .unwrap();
    let signed = json!({
        "op": "sign_with_label", "seed_hex": hex(&seed),
        "public_key_hex": hex(&signature_public_key(&seed)),
        "label": "GroupInfoTBS", "content_hex": hex(&content), "signature_hex": hex(&signature),
    });
    let mut tampered = signature.clone();
    tampered[0] ^= 1;

    let kem_seed = fixed("rust kem seed", 64);
    let public = suite.kem_public_key(&kem_seed).unwrap();
    let context = fixed("rust context", 40);
    let plaintext = fixed("rust commit secret", 48);
    let sealed = suite
        .encrypt_with_label(&public, "UpdatePathNode", &context, &plaintext)
        .unwrap();
    let encrypted = json!({
        "op": "encrypt_with_label", "seed_hex": hex(&kem_seed), "public_key_hex": hex(&public),
        "label": "UpdatePathNode", "context_hex": hex(&context), "plaintext_hex": hex(&plaintext),
        "kem_output_hex": hex(&sealed.kem_output), "ciphertext_hex": hex(&sealed.ciphertext),
    });
    let mut flipped = sealed.ciphertext.clone();
    *flipped.last_mut().unwrap() ^= 1;

    let xwing = CipherSuite::XWING;
    let xwing_seed = fixed("rust xwing seed", 32);
    let xwing_public = xwing.kem_public_key(&xwing_seed).unwrap();
    let xwing_context = fixed("rust xwing context", 40);
    let xwing_plaintext = fixed("rust xwing commit secret", 32);
    let xwing_sealed = xwing
        .encrypt_with_label(
            &xwing_public,
            "UpdatePathNode",
            &xwing_context,
            &xwing_plaintext,
        )
        .unwrap();
    let xwing_encrypted = json!({
        "op": "encrypt_with_label", "cipher_suite": xwing.0, "seed_hex": hex(&xwing_seed),
        "public_key_hex": hex(&xwing_public), "label": "UpdatePathNode",
        "context_hex": hex(&xwing_context), "plaintext_hex": hex(&xwing_plaintext),
        "kem_output_hex": hex(&xwing_sealed.kem_output), "ciphertext_hex": hex(&xwing_sealed.ciphertext),
    });
    let mut xwing_flipped = xwing_sealed.kem_output.clone();
    *xwing_flipped.last_mut().unwrap() ^= 1;

    let document = json!({
        "library": "moqom-mls",
        "description": "RFC 9420 §5 SignWithLabel and EncryptWithLabel as the Rust crate produces them over aws-lc-rs: suite 0xF0AA (ML-DSA-65; HPKE KEM 0x0041, KDF 0x0002, AEAD 0x0002), and, for cases whose cipher_suite is 61601, suite 0xF0A1 (HPKE KEM 0x647a, X-Wing; KDF 0x0001, AEAD 0x0001) with X-Wing's 32-byte seed, composed in rust/moqom-mls/src/hpke.rs and src/xwing.rs. Same fields as mls-crypto.json.",
        "source": "Generated by moqom-mls (Rust, aws-lc-rs): rust/moqom-mls/tests/generate.rs. A recorded transcript: AWS-LC takes no caller randomness.",
        "cases": [
            with(&signed, json!({"name": "rust-sign-with-label"})),
            with(&signed, json!({"name": "rust-sign-with-label-tampered", "signature_hex": hex(&tampered), "error": "bad-signature"})),
            with(&encrypted, json!({"name": "rust-encrypt-with-label"})),
            with(&encrypted, json!({"name": "rust-encrypt-with-label-tampered", "ciphertext_hex": hex(&flipped), "error": "decryption-failed"})),
            with(&xwing_encrypted, json!({"name": "rust-xwing-encrypt-with-label"})),
            with(&xwing_encrypted, json!({"name": "rust-xwing-encrypt-with-label-tampered-x25519", "kem_output_hex": hex(&xwing_flipped), "error": "decryption-failed"})),
        ],
    });
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../vectors/mls/mls-crypto-rust.json"
    );
    std::fs::write(
        path,
        serde_json::to_string_pretty(&document).unwrap() + "\n",
    )
    .unwrap();
}

fn signature_public_key(seed: &[u8]) -> Vec<u8> {
    use aws_lc_rs::signature::{KeyPair, ML_DSA_65_SIGNING, PqdsaKeyPair};
    PqdsaKeyPair::from_seed(&ML_DSA_65_SIGNING, seed)
        .unwrap()
        .public_key()
        .as_ref()
        .to_vec()
}
